// What the page's interface is made of, gathered from the tables that define it, as plain data:
// the headless tools (which cannot import the page's TypeScript) read it from a committed file,
// tools/headless/schema.json, which `npm run gen` writes and a unit test keeps up to date.
import { COOLING_LABELS } from '../cooling/cooling';
import { EOS_LABELS } from '../eos/eos';
import { VARIABLES } from '../io/snapshot';
import { GRAVITY_MODES, LIMITER_KINDS, RIEMANN_KINDS } from '../problems/types';
import { VIEW_EXTRAS, VIEW_OPTIONS, type ViewOption } from '../render/view_options';
import { API_METHODS } from '../ui/api_schema';
import { linkKeys } from '../ui/link';

export function buildSchema() {
  return {
    about: 'Generated by `npm run gen` from the tables in src (the option table, the view options, the link codec). Do not edit: change the table and run it again.',
    /** what a setting with a fixed list of choices may hold */
    choices: {
      eos: Object.keys(EOS_LABELS),
      cooling: Object.keys(COOLING_LABELS),
      riemann: [...RIEMANN_KINDS],
      limiter: [...LIMITER_KINDS],
      gravity: [...GRAVITY_MODES],
    },
    /** what stats, slice and probe can read (besides a species' name) */
    variables: [...VARIABLES, 'level'],
    /** every key of a setup given as a query string or a flat object */
    link: linkKeys().map(({ key, group, about }) => ({ key, group, about })),
    /** every setting of the view, as `view()` names it and as a link does */
    view: [
      ...VIEW_OPTIONS.map((o: ViewOption) => ({ key: o.key, link: o.link, type: o.type, ...(o.min !== undefined ? { min: o.min } : {}), ...(o.max !== undefined ? { max: o.max } : {}), about: o.doc })),
      ...VIEW_EXTRAS.map((o) => ({ key: o.key, link: o.link, type: 'extra', about: o.doc })),
    ],
    /** the methods of `window.shaderous`: what each does, and its arguments as JSON Schema */
    api: API_METHODS,
  };
}

/** The file's text: stable, so that a change shows as a small diff. */
export const schemaText = () => `${JSON.stringify(buildSchema(), null, 1)}\n`;
