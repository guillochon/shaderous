"""Write a trained burner (a 'flow2f' Burner) into the simulator: src/burn/aprox13_net.ts holds
its weights and everything its inputs are computed from (the REACLIB fits of every rate term,
the screening pairs, the nuclear energies), and src/burn/aprox13_net_cases.json holds steps
computed here, which the TypeScript mirror (src/burn/network.ts) is tested against.

    tools/burn/.venv/Scripts/python tools/burn/export_net.py [model.pt]   (default model_dagger_30.pt)

The weights are stored in half precision, as they were scored (score.py), and the cases are
computed with the weights rounded the same way.
"""
import base64
import json
import sys
from pathlib import Path

import numpy as np
import torch
from torch import nn

import train

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "src" / "burn" / "aprox13_net.ts"
CASES = ROOT / "src" / "burn" / "aprox13_net_cases.json"
NAMES = ["he4", "c12", "o16", "ne20", "mg24", "si28", "s32", "ar36", "ca40", "ti44", "cr48", "fe52", "ni56"]


def rate_spec(rate):
    """A FULL_TERMS rate as data: the REACLIB sets of each rate it needs and its screening."""
    if rate[0] == "approx":
        _, way, a, b, mid = rate
        names = {
            "ag": f"{a}_He4_to_{b}_reaclib", "ap": f"{a}_He4_to_p_{mid}_reaclib",
            "pg": f"{mid}_p_to_{b}_reaclib", "pa": f"{mid}_p_to_He4_{a}_reaclib",
            "ga": f"{b}_to_He4_{a}_reaclib", "gp": f"{b}_to_p_{mid}_reaclib",
        }
        return {"approx": way, "sets": {k: train.reaclib_sets(v) for k, v in names.items()},
                "alpha": f"He4_{a}", "proton": f"p_{mid}"}
    name, pairs = rate
    return {"sets": train.reaclib_sets(name), "screen": pairs}


def main():
    name = sys.argv[1] if len(sys.argv) > 1 else "model_dagger_30.pt"
    model = train.load_model(name)
    assert model.arch == "flow2f", model.arch
    with torch.no_grad():
        for p in model.parameters():
            p.copy_(p.half().float())
    lin = [m for m in model.net if isinstance(m, nn.Linear)]
    layers = [[m.in_features, m.out_features] for m in lin]
    flat = np.concatenate([np.concatenate([m.weight.detach().cpu().numpy().ravel(), m.bias.detach().cpu().numpy()]) for m in lin])
    b64 = base64.b64encode(flat.astype("<f2").tobytes()).decode()
    terms = [{"coef": c, "powers": [[i, n] for i, n in pw.items()], "nrho": nr, "rate": rate_spec(r)}
             for c, pw, nr, r in train.FULL_TERMS]
    data = {
        "names": NAMES,
        "A": train.A.tolist(),
        "Z": train.ZS.tolist(),
        "q": train.nuclear_q().tolist(),
        "logRho": list(train.LOG_RHO), "logT": list(train.LOG_T), "logDt": list(train.LOG_DT),
        "screenPairs": {k: list(v) for k, v in train.SCREEN_PAIRS.items()},
        "co2": train.CO2, "aaFac": train.AA_FAC,
        "terms": terms,
        "layers": layers,
    }
    OUT.write_text(
        "// Generated by tools/burn/export_net.py from tools/burn/" + name + ": do not edit.\n"
        "// The trained burner of the 13-isotope alpha chain (src/burn/network.ts): its weights,\n"
        "// little-endian half precision, every layer's weight matrix (rows of outputs) and then its\n"
        "// bias; and the data its inputs are computed from.\n"
        f"export const NET_DATA = {json.dumps(data)} as const;\n"
        f"export const NET_WEIGHTS_F16 = '{b64}';\n",
        encoding="utf-8")

    # Cases: states from the held-out targeted trajectories and the general set, at assorted
    # times and steps.
    rng = np.random.default_rng(3)
    tt = np.load(train.HERE / "targets_test.npz")
    rho, X, T = tt["rho"], tt["X"], tt["T"]
    i = rng.choice(len(rho), size=48, replace=False)
    k = rng.integers(0, X.shape[1] - 1, size=48)
    lr = np.log10(rho[i]).astype(np.float32)
    lT = np.log10(T[i, k]).astype(np.float32)
    ld = rng.uniform(-8.0, -1.0, size=48).astype(np.float32)
    Xs = X[i, k].astype(np.float32)
    f = lambda a: torch.tensor(a, device=train.dev)
    with torch.no_grad():
        feats = train.features(f(lr), f(lT), f(ld), f(Xs), "full").cpu().numpy()
        D = model(f(lr), f(lT), f(ld), f(Xs)).cpu().numpy()
    cases = [{"logRho": float(a), "logT": float(b), "logDt": float(c), "X": x.tolist(), "features": g.tolist(), "D": d.tolist()}
             for a, b, c, x, g, d in zip(lr, lT, ld, Xs, feats, D)]
    CASES.write_text(json.dumps(cases))
    print(f"wrote {OUT} ({len(b64) // 1024} KB of weights) and {len(cases)} cases to {CASES}")


if __name__ == "__main__":
    main()
