"""Write a trained closure into the simulator: src/closure/closure_net.ts holds its weights and
the constants of its features and gates (closure.py's, so the shader and the TypeScript mirror
cannot drift from what was trained), and src/closure/closure_cases.json holds cells computed
here, which the mirror (src/closure/closure.ts) is tested against.

    tools/closure/.venv/bin/python tools/closure/export.py [model]   (default: final)

Only the jump-scaling heads (a, b) are exported: the simulator's closure has no eddy viscosity
(the trained models leave it at nothing: docs/closure.md), so a model that uses those heads is
refused.
"""
import base64
import json
import sys
from pathlib import Path

import numpy as np
import torch

import closure as C
from closure import Closure, features
from solver import Config, primitives

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = ROOT / "src" / "closure" / "closure_net.ts"
CASES = ROOT / "src" / "closure" / "closure_cases.json"


def load_model(name):
    ck = torch.load(HERE / "models" / f"{name}.pt")
    model = Closure(ck["hidden"], ck["layers"], ck["heads"])
    model.load_state_dict(ck["state"])
    model.eval()
    return model, ck


def main():
    name = sys.argv[1] if len(sys.argv) > 1 else "final"
    model, ck = load_model(name)
    if set(ck["heads"]) - set("ab"):
        raise SystemExit(f"{name} uses the heads '{ck['heads']}': the simulator's closure has only a and b")
    model = model.double()
    flat = np.concatenate([np.concatenate([m.weight.detach().numpy().ravel(), m.bias.detach().numpy()]) for m in model.net])
    # The weights as the shader holds them: single precision.
    flat = flat.astype("<f4")
    with torch.no_grad():
        o = 0
        for m in model.net:
            nw = m.weight.numel()
            m.weight.copy_(torch.from_numpy(flat[o : o + nw].astype(np.float64)).view_as(m.weight))
            m.bias.copy_(torch.from_numpy(flat[o + nw : o + nw + m.bias.numel()].astype(np.float64)))
            o += nw + m.bias.numel()
    data = {
        "model": name,
        "features": C.N_FEATURES,
        "hidden": ck["hidden"],
        "layers": ck["layers"],
        "heads": [float("a" in ck["heads"]), float("b" in ck["heads"])],
        "aMax": C.A_MAX, "bMax": C.B_MAX,
        "ducros": list(C.DUCROS), "jump": list(C.JUMP), "active": list(C.ACTIVE), "epsV": C.EPS_V,
    }
    OUT.write_text(
        f"// Generated by tools/closure/export.py from tools/closure/models/{name}.pt: do not edit.\n"
        "// The trained turbulence closure (src/closure/closure.ts): its weights, little-endian single\n"
        "// precision, every layer's weight matrix (rows of outputs) and then its bias; and the\n"
        "// constants of its features, gates and outputs.\n"
        f"export const CLOSURE_DATA = {json.dumps(data)} as const;\n"
        f"export const CLOSURE_WEIGHTS_F32 = '{base64.b64encode(flat.tobytes()).decode()}';\n",
        encoding="utf-8")

    # Cases: cells of the held-out trajectories at assorted times (turbulence, shear layers),
    # and cells of a planar shock and a contact, where the gates must shut.
    rng = np.random.default_rng(5)
    cfg = Config()
    states = []
    for f in sorted((HERE / "data" / "test").glob("*.npz"))[:4]:
        d = np.load(f)
        for k in rng.integers(1, len(d["t"]), 2):
            states.append(torch.from_numpy(d["U"][k]).double())
    n = states[0].shape[-1]
    x = (torch.arange(n, dtype=torch.float64) + 0.5) / n
    X = x.view(1, n).expand(n, n)
    step = 0.5 * (1 + torch.tanh((X - 0.5) / (1.5 / n)))
    # A Mach 3 shock moving along x (post-shock gas on the left), smeared over three cells.
    g = cfg.gamma
    rho2, u2, p2 = (g + 1) * 9 / ((g - 1) * 9 + 2), 3 * np.sqrt(g) * (1 - ((g - 1) * 9 + 2) / ((g + 1) * 9)), 1 + 2 * g / (g + 1) * 8
    rho, u, p = rho2 + (1 - rho2) * step, u2 * (1 - step), p2 + (1 - p2) * step
    ei = p / (g - 1)
    states.append(torch.stack([rho, rho * u, torch.zeros_like(rho), ei + 0.5 * rho * u * u, ei, rho * (1 - step)]))
    # A contact at rest: a jump in density and scalar, nothing moving.
    rho = 1 + step
    ei = torch.ones_like(rho) / (g - 1)
    states.append(torch.stack([rho, torch.zeros_like(rho), torch.zeros_like(rho), ei, ei, rho * step]))
    cases = []
    for U in states:
        U = U.double().unsqueeze(0)
        rho, vx, vy, p, s, cs = primitives(U, cfg)
        dx = cfg.box / n
        with torch.no_grad():
            F, gate, A = features(rho, vx, vy, p, s, cs, dx)
            Cf = model(rho, vx, vy, p, s, cs, dx)
        picks = [(int(j), int(i)) for j, i in zip(rng.integers(0, n, 12), rng.integers(0, n, 12))]
        # Around the middle of the box too: where the synthetic jumps are.
        picks += [(int(j), n // 2 + d) for j, d in zip(rng.integers(0, n, 4), (-2, -1, 0, 1))]
        for j, i in picks:
            def at(q, dj=0, di=0):
                return float(q[0, (j + dj) % n, (i + di) % n])

            def cell(dj, di):
                return {"rho": at(rho, dj, di), "vx": at(vx, dj, di), "vy": at(vy, dj, di), "p": at(p, dj, di), "s": at(s, dj, di)}

            cases.append({
                "c": cell(0, 0), "xm": cell(0, -1), "xp": cell(0, 1), "ym": cell(-1, 0), "yp": cell(1, 0), "cs": at(cs),
                "features": [float(F[0, k, j, i]) for k in range(C.N_FEATURES)],
                "gate": float(gate[0, j, i]), "a": float(Cf[0, 0, j, i]), "b": float(Cf[0, 1, j, i]),
            })
    CASES.write_text(json.dumps(cases, separators=(",", ":")) + "\n")
    shut = sum(1 for c in cases if c["gate"] == 0)
    print(f"{OUT.name}: {flat.size} weights from {name}; {CASES.name}: {len(cases)} cells, {shut} with the gate shut")


if __name__ == "__main__":
    main()
